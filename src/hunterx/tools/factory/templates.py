#: The standard template shipped with the factory.
BUILTIN_TEMPLATE = IntegrationTemplate(
    template_id="standard",
    name="Standard Integration Template",
    description="Default HunterX Tool Integration Pack layout and boilerplate.",
    version="1.0.0",
    structure_version=PACK_STRUCTURE_VERSION,
    author="HunterX Team",
    files=dict(_BUILTIN_FILES),
    builtin=True,
)


class PackTemplateStore:
    """Holds integration templates and resolves the effective file set.

    A :class:`PackTemplateRepository` may back the store; registered overrides
    take precedence over the built-in standard template.
    """

    def __init__(self, repository: PackTemplateRepository | None = None) -> None:
        self._repository = repository
        self._overrides: dict[str, IntegrationTemplate] = {}

    def register(self, template: IntegrationTemplate) -> IntegrationTemplate:
        """Register a template override (persisting it when backed)."""
        self._overrides[template.template_id] = template
        if self._repository is not None:
            self._repository.save(template)
        return template

    def get(self, template_id: str) -> IntegrationTemplate:
        """Return a template, raising :class:`TemplateNotFoundError`."""
        if template_id in self._overrides:
            return self._overrides[template_id]
        if template_id == "standard" or template_id is None:
            return BUILTIN_TEMPLATE
        if self._repository is not None:
            template = self._repository.get(template_id)
            if template is not None:
                self._overrides[template_id] = template
                return template
        raise TemplateNotFoundError(template_id)

    def resolve(self, template_id: str | None = None) -> dict[str, str]:
        """Return the effective ``path -> template content`` file set.

        The built-in standard template is the base; a chosen template's files
        override it per path.
        """
        files: dict[str, str] = dict(BUILTIN_TEMPLATE.files)
        if template_id is not None and template_id != "standard":
            template = self.get(template_id)
            files.update(template.files)
        return files

    def list(self) -> list[IntegrationTemplate]:
        """Return every known template (built-in plus registered overrides)."""
        templates = [BUILTIN_TEMPLATE]
        if self._repository is not None:
            templates.extend(self._repository.list(limit=10_000))
        templates.extend(self._overrides.values())
        seen: dict[str, IntegrationTemplate] = {}
        for template in templates:
            seen[template.template_id] = template
        return list(seen.values())
