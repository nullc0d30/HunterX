_NORMALIZER = '''# ${copyright}
# SPDX-License-Identifier: Apache-2.0

"""Normalizer for ${display_name} findings.

Generated by the HunterX Tool Integration Factory v${generator_version}.
"""

from __future__ import annotations

from typing import Any

from hunterx.plugins.sdk.results import FindingResult


class ${normalizer_class_name}:
    """Normalizes ${tool_name} records into :class:`FindingResult`."""

    def normalize(self, records: list[dict[str, Any]], *, target: str) -> list[FindingResult]:
        """Convert parsed records into normalized findings."""
        return [self._normalize(record, target=target) for record in records]

    def _normalize(self, record: dict[str, Any], *, target: str) -> FindingResult:
        return FindingResult(
            title=str(record.get("title", "Finding")),
            severity=str(record.get("severity", "info")).lower(),
            target=str(record.get("target", target)),
            description=str(record.get("description", "")),
            risk_score=self._risk_score(record),
            metadata=dict(record.get("metadata", {})),
        )

    @staticmethod
    def _risk_score(record: dict[str, Any]) -> float | None:
        score = record.get("risk_score")
        if score is None:
            return None
        try:
            return float(score)
        except (TypeError, ValueError):
            return None
'''

